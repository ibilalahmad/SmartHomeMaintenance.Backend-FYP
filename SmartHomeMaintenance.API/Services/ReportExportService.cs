using ClosedXML.Excel;
using QuestPDF.Fluent;
using QuestPDF.Helpers;
using QuestPDF.Infrastructure;
using SmartHomeMaintenance.API.Models;
using System;
using System.IO;
using System.Linq;

namespace SmartHomeMaintenance.API.Services
{
    public interface IReportExportService
    {
        byte[] GenerateExcelReport(ExportReportRequestDto report);
        byte[] GeneratePdfReport(ExportReportRequestDto report);
    }

    public class ReportExportService : IReportExportService
    {
        static ReportExportService()
        {
            // QuestPDF Community License configuration
            QuestPDF.Settings.License = LicenseType.Community;
            QuestPDF.Settings.UseSystemFonts = true;
            QuestPDF.Settings.ThrowOnMissingFontFamilies = false;
        }

        public byte[] GenerateExcelReport(ExportReportRequestDto report)
        {
            using var workbook = new XLWorkbook();
            var ws = workbook.Worksheets.Add("SHMS Report");
            ws.ShowGridLines = true;

            var title = report.ReportType == "CustomerActivity" 
                ? "Customer Activity & Engagement Report" 
                : "Service Provider Performance Report";

            // Title Block
            ws.Cell("A1").Value = "Smart Home Maintenance Service (SHMS)";
            ws.Cell("A1").Style.Font.Bold = true;
            ws.Cell("A1").Style.Font.FontSize = 16;
            ws.Cell("A1").Style.Font.FontColor = XLColor.FromArgb(30, 58, 138); // Deep Navy

            ws.Cell("A2").Value = title;
            ws.Cell("A2").Style.Font.Bold = true;
            ws.Cell("A2").Style.Font.FontSize = 13;
            ws.Cell("A2").Style.Font.FontColor = XLColor.FromArgb(71, 85, 105);

            // Metadata
            ws.Cell("A4").Value = "Generated On:";
            ws.Cell("B4").Value = DateTime.UtcNow.ToString("yyyy-MM-dd HH:mm:ss") + " UTC";
            ws.Cell("A5").Value = "Date Range:";
            ws.Cell("B5").Value = $"{report.StartDate ?? "All Time"} to {report.EndDate ?? "All Time"}";
            ws.Cell("A6").Value = "Generated By:";
            ws.Cell("B6").Value = report.GeneratedBy ?? "Bilal Ahmed (Admin)";

            for (int r = 4; r <= 6; r++)
            {
                ws.Cell(r, 1).Style.Font.Bold = true;
                ws.Cell(r, 1).Style.Font.FontColor = XLColor.FromArgb(100, 116, 139);
            }

            int currentRow = 8;

            // KPI Summary Section
            ws.Cell(currentRow, 1).Value = "EXECUTIVE SUMMARY & KPIS";
            ws.Cell(currentRow, 1).Style.Font.Bold = true;
            ws.Cell(currentRow, 1).Style.Font.FontColor = XLColor.FromArgb(30, 58, 138);
            currentRow++;

            if (report.BookingSummary != null)
            {
                var summaryHeaders = new[] { "Total Bookings", "Completed", "Cancelled", "Pending", "Success Rate" };
                for (int i = 0; i < summaryHeaders.Length; i++)
                {
                    var cell = ws.Cell(currentRow, i + 1);
                    cell.Value = summaryHeaders[i];
                    cell.Style.Font.Bold = true;
                    cell.Style.Fill.BackgroundColor = XLColor.FromArgb(241, 245, 249);
                    cell.Style.Border.OutsideBorder = XLBorderStyleValues.Thin;
                    cell.Style.Border.OutsideBorderColor = XLColor.FromArgb(203, 213, 225);
                }
                currentRow++;

                ws.Cell(currentRow, 1).Value = report.BookingSummary.Total;
                ws.Cell(currentRow, 2).Value = report.BookingSummary.Completed;
                ws.Cell(currentRow, 3).Value = report.BookingSummary.Cancelled;
                ws.Cell(currentRow, 4).Value = report.BookingSummary.Pending;
                ws.Cell(currentRow, 5).Value = $"{report.BookingSummary.SuccessRate:0.0}%";

                for (int i = 1; i <= summaryHeaders.Length; i++)
                {
                    var cell = ws.Cell(currentRow, i);
                    cell.Style.Font.Bold = true;
                    cell.Style.Alignment.Horizontal = XLAlignmentHorizontalValues.Center;
                    cell.Style.Border.OutsideBorder = XLBorderStyleValues.Thin;
                    cell.Style.Border.OutsideBorderColor = XLColor.FromArgb(203, 213, 225);
                }
                currentRow += 2;
            }

            // Customer Summary if Customer Activity
            if (report.ReportType == "CustomerActivity" && report.CustomerSummary != null)
            {
                var custHeaders = new[] { "Total Registered", "Active Users", "Avg Bookings / User" };
                for (int i = 0; i < custHeaders.Length; i++)
                {
                    var cell = ws.Cell(currentRow, i + 1);
                    cell.Value = custHeaders[i];
                    cell.Style.Font.Bold = true;
                    cell.Style.Fill.BackgroundColor = XLColor.FromArgb(241, 245, 249);
                    cell.Style.Border.OutsideBorder = XLBorderStyleValues.Thin;
                }
                currentRow++;

                ws.Cell(currentRow, 1).Value = report.CustomerSummary.TotalRegistered;
                ws.Cell(currentRow, 2).Value = report.CustomerSummary.ActiveLast3Months;
                ws.Cell(currentRow, 3).Value = report.CustomerSummary.AverageBookingsPerCustomer.ToString("0.00");

                for (int i = 1; i <= custHeaders.Length; i++)
                {
                    var cell = ws.Cell(currentRow, i);
                    cell.Style.Font.Bold = true;
                    cell.Style.Alignment.Horizontal = XLAlignmentHorizontalValues.Center;
                    cell.Style.Border.OutsideBorder = XLBorderStyleValues.Thin;
                }
                currentRow += 2;
            }

            // Main Data Table
            if (report.ReportType == "CustomerActivity")
            {
                var headers = new[] { "ID", "Customer Name", "Email Address", "Phone Number", "Location / Address", "Bookings", "Complaints", "Status" };
                for (int i = 0; i < headers.Length; i++)
                {
                    var cell = ws.Cell(currentRow, i + 1);
                    cell.Value = headers[i];
                    cell.Style.Font.Bold = true;
                    cell.Style.Font.FontColor = XLColor.White;
                    cell.Style.Fill.BackgroundColor = XLColor.FromArgb(30, 58, 138);
                    cell.Style.Alignment.Horizontal = XLAlignmentHorizontalValues.Center;
                    cell.Style.Border.OutsideBorder = XLBorderStyleValues.Thin;
                }
                currentRow++;

                if (report.CustomerItems != null && report.CustomerItems.Count > 0)
                {
                    int idx = 0;
                    foreach (var item in report.CustomerItems)
                    {
                        ws.Cell(currentRow, 1).Value = item.Id;
                        ws.Cell(currentRow, 2).Value = item.Name;
                        ws.Cell(currentRow, 3).Value = item.Email;
                        ws.Cell(currentRow, 4).Value = item.Phone;
                        ws.Cell(currentRow, 5).Value = item.Location;
                        ws.Cell(currentRow, 6).Value = item.BookingsCount;
                        ws.Cell(currentRow, 7).Value = item.ComplaintsCount;
                        ws.Cell(currentRow, 8).Value = item.Status;

                        var bg = (idx % 2 == 0) ? XLColor.White : XLColor.FromArgb(248, 250, 252);
                        for (int col = 1; col <= 8; col++)
                        {
                            var cell = ws.Cell(currentRow, col);
                            cell.Style.Fill.BackgroundColor = bg;
                            cell.Style.Border.OutsideBorder = XLBorderStyleValues.Thin;
                            cell.Style.Border.OutsideBorderColor = XLColor.FromArgb(226, 232, 240);
                            if (col == 1 || col == 6 || col == 7 || col == 8)
                                cell.Style.Alignment.Horizontal = XLAlignmentHorizontalValues.Center;
                        }
                        currentRow++;
                        idx++;
                    }
                }
                else
                {
                    ws.Cell(currentRow, 1).Value = "No customer activity records found for this period.";
                    ws.Range(currentRow, 1, currentRow, 8).Merge();
                    ws.Cell(currentRow, 1).Style.Alignment.Horizontal = XLAlignmentHorizontalValues.Center;
                    ws.Cell(currentRow, 1).Style.Font.Italic = true;
                    currentRow++;
                }
            }
            else
            {
                // SP Performance
                var headers = new[] { "ID", "Provider Name", "Specialization / Expertise", "Hourly Rate (PKR)", "Completed Jobs", "Avg Rating", "Complaints", "Status" };
                for (int i = 0; i < headers.Length; i++)
                {
                    var cell = ws.Cell(currentRow, i + 1);
                    cell.Value = headers[i];
                    cell.Style.Font.Bold = true;
                    cell.Style.Font.FontColor = XLColor.White;
                    cell.Style.Fill.BackgroundColor = XLColor.FromArgb(30, 58, 138);
                    cell.Style.Alignment.Horizontal = XLAlignmentHorizontalValues.Center;
                    cell.Style.Border.OutsideBorder = XLBorderStyleValues.Thin;
                }
                currentRow++;

                if (report.SpPerformance != null && report.SpPerformance.Count > 0)
                {
                    int idx = 0;
                    foreach (var item in report.SpPerformance)
                    {
                        ws.Cell(currentRow, 1).Value = item.Id;
                        ws.Cell(currentRow, 2).Value = item.Name;
                        ws.Cell(currentRow, 3).Value = item.Expertise ?? "General";
                        ws.Cell(currentRow, 4).Value = item.HourlyRate;
                        ws.Cell(currentRow, 5).Value = item.CompletedJobs;
                        ws.Cell(currentRow, 6).Value = item.AverageRating.ToString("0.0");
                        ws.Cell(currentRow, 7).Value = item.ComplaintsReceived;
                        ws.Cell(currentRow, 8).Value = item.Status;

                        var bg = (idx % 2 == 0) ? XLColor.White : XLColor.FromArgb(248, 250, 252);
                        for (int col = 1; col <= 8; col++)
                        {
                            var cell = ws.Cell(currentRow, col);
                            cell.Style.Fill.BackgroundColor = bg;
                            cell.Style.Border.OutsideBorder = XLBorderStyleValues.Thin;
                            cell.Style.Border.OutsideBorderColor = XLColor.FromArgb(226, 232, 240);
                            if (col == 1 || col == 4 || col == 5 || col == 6 || col == 7 || col == 8)
                                cell.Style.Alignment.Horizontal = XLAlignmentHorizontalValues.Center;
                        }
                        currentRow++;
                        idx++;
                    }
                }
                else
                {
                    ws.Cell(currentRow, 1).Value = "No service provider performance records found for this period.";
                    ws.Range(currentRow, 1, currentRow, 8).Merge();
                    ws.Cell(currentRow, 1).Style.Alignment.Horizontal = XLAlignmentHorizontalValues.Center;
                    ws.Cell(currentRow, 1).Style.Font.Italic = true;
                    currentRow++;
                }
            }

            // Adjust column widths
            ws.Columns().AdjustToContents();

            using var stream = new MemoryStream();
            workbook.SaveAs(stream);
            return stream.ToArray();
        }

        public byte[] GeneratePdfReport(ExportReportRequestDto report)
        {
            var isCustomer = report.ReportType == "CustomerActivity";
            var title = isCustomer ? "Customer Activity Report" : "Service Provider Performance Report";
            var generatedDateStr = DateTime.UtcNow.ToString("dd MMM yyyy, HH:mm") + " UTC";
            var dateRangeStr = $"{report.StartDate ?? "Start"} to {report.EndDate ?? "End"}";
            var generatedByStr = report.GeneratedBy ?? "Bilal Ahmed (Admin)";

            var document = Document.Create(container =>
            {
                container.Page(page =>
                {
                    page.Size(PageSizes.A4);
                    page.Margin(1.5f, Unit.Centimetre);
                    page.PageColor(Colors.White);
                    page.DefaultTextStyle(x => x.FontSize(9));

                    // Header
                    page.Header().Column(col =>
                    {
                        col.Item().Row(row =>
                        {
                            row.RelativeItem().Column(titleCol =>
                            {
                                titleCol.Item().Text("Smart Home Maintenance Service (SHMS)")
                                    .FontSize(15).Bold().FontColor("#1E3A8A");
                                titleCol.Item().Text(title)
                                    .FontSize(12).SemiBold().FontColor("#475569");
                            });

                            row.ConstantItem(180).AlignRight().Column(metaCol =>
                            {
                                metaCol.Item().Text($"Date: {generatedDateStr}").FontSize(8).FontColor("#64748B");
                                metaCol.Item().Text($"Range: {dateRangeStr}").FontSize(8).FontColor("#64748B");
                                metaCol.Item().Text($"Admin: {generatedByStr}").FontSize(8).FontColor("#64748B");
                            });
                        });

                        col.Item().PaddingTop(8).LineHorizontal(1.5f).LineColor("#1E3A8A");
                        col.Item().PaddingBottom(12);
                    });

                    // Body Content
                    page.Content().Column(col =>
                    {
                        // KPI Cards
                        if (report.BookingSummary != null)
                        {
                            col.Item().PaddingBottom(6).Text("EXECUTIVE METRICS").Bold().FontSize(10).FontColor("#1E3A8A");
                            col.Item().PaddingBottom(14).Row(row =>
                            {
                                row.RelativeItem().Border(1).BorderColor("#CBD5E1").Background("#F8FAFC").Padding(8).Column(c =>
                                {
                                    c.Item().Text("Total Bookings").FontSize(8).FontColor("#64748B").Bold();
                                    c.Item().Text(report.BookingSummary.Total.ToString()).FontSize(14).Bold().FontColor("#0F172A");
                                });
                                row.Spacing(8);

                                row.RelativeItem().Border(1).BorderColor("#CBD5E1").Background("#F8FAFC").Padding(8).Column(c =>
                                {
                                    c.Item().Text("Completed Jobs").FontSize(8).FontColor("#64748B").Bold();
                                    c.Item().Text(report.BookingSummary.Completed.ToString()).FontSize(14).Bold().FontColor("#16A34A");
                                });
                                row.Spacing(8);

                                row.RelativeItem().Border(1).BorderColor("#CBD5E1").Background("#F8FAFC").Padding(8).Column(c =>
                                {
                                    c.Item().Text("Cancelled").FontSize(8).FontColor("#64748B").Bold();
                                    c.Item().Text(report.BookingSummary.Cancelled.ToString()).FontSize(14).Bold().FontColor("#DC2626");
                                });
                                row.Spacing(8);

                                row.RelativeItem().Border(1).BorderColor("#CBD5E1").Background("#F8FAFC").Padding(8).Column(c =>
                                {
                                    c.Item().Text("Success Rate").FontSize(8).FontColor("#64748B").Bold();
                                    c.Item().Text($"{report.BookingSummary.SuccessRate:0.0}%").FontSize(14).Bold().FontColor("#2563EB");
                                });
                            });
                        }

                        // Table Section
                        col.Item().PaddingBottom(6).Text(isCustomer ? "CUSTOMER ACCOUNTS & ACTIVITY" : "SERVICE PROVIDER DIRECTORY & PERFORMANCE")
                            .Bold().FontSize(10).FontColor("#1E3A8A");

                        col.Item().Table(table =>
                        {
                            if (isCustomer)
                            {
                                table.ColumnsDefinition(columns =>
                                {
                                    columns.ConstantColumn(30);  // ID
                                    columns.RelativeColumn(3);  // Name
                                    columns.RelativeColumn(3);  // Email
                                    columns.RelativeColumn(2);  // Phone
                                    columns.RelativeColumn(2);  // Location
                                    columns.ConstantColumn(45); // Bookings
                                    columns.ConstantColumn(45); // Complaints
                                    columns.ConstantColumn(50); // Status
                                });

                                // Header
                                table.Header(header =>
                                {
                                    header.Cell().Background("#1E3A8A").Padding(5).AlignCenter().Text("ID").Bold().FontColor("#FFFFFF");
                                    header.Cell().Background("#1E3A8A").Padding(5).Text("Customer Name").Bold().FontColor("#FFFFFF");
                                    header.Cell().Background("#1E3A8A").Padding(5).Text("Email").Bold().FontColor("#FFFFFF");
                                    header.Cell().Background("#1E3A8A").Padding(5).Text("Phone").Bold().FontColor("#FFFFFF");
                                    header.Cell().Background("#1E3A8A").Padding(5).Text("Location").Bold().FontColor("#FFFFFF");
                                    header.Cell().Background("#1E3A8A").Padding(5).AlignCenter().Text("Jobs").Bold().FontColor("#FFFFFF");
                                    header.Cell().Background("#1E3A8A").Padding(5).AlignCenter().Text("Issues").Bold().FontColor("#FFFFFF");
                                    header.Cell().Background("#1E3A8A").Padding(5).AlignCenter().Text("Status").Bold().FontColor("#FFFFFF");
                                });

                                // Rows
                                if (report.CustomerItems != null && report.CustomerItems.Count > 0)
                                {
                                    for (int i = 0; i < report.CustomerItems.Count; i++)
                                    {
                                        var item = report.CustomerItems[i];
                                        var bg = (i % 2 == 0) ? "#FFFFFF" : "#F8FAFC";

                                        table.Cell().Background(bg).BorderBottom(1).BorderColor("#E2E8F0").Padding(4).AlignCenter().Text(item.Id);
                                        table.Cell().Background(bg).BorderBottom(1).BorderColor("#E2E8F0").Padding(4).Text(item.Name).Bold();
                                        table.Cell().Background(bg).BorderBottom(1).BorderColor("#E2E8F0").Padding(4).Text(item.Email);
                                        table.Cell().Background(bg).BorderBottom(1).BorderColor("#E2E8F0").Padding(4).Text(item.Phone);
                                        table.Cell().Background(bg).BorderBottom(1).BorderColor("#E2E8F0").Padding(4).Text(item.Location);
                                        table.Cell().Background(bg).BorderBottom(1).BorderColor("#E2E8F0").Padding(4).AlignCenter().Text(item.BookingsCount.ToString());
                                        table.Cell().Background(bg).BorderBottom(1).BorderColor("#E2E8F0").Padding(4).AlignCenter().Text(item.ComplaintsCount.ToString());
                                        table.Cell().Background(bg).BorderBottom(1).BorderColor("#E2E8F0").Padding(4).AlignCenter().Text(item.Status);
                                    }
                                }
                            }
                            else
                            {
                                table.ColumnsDefinition(columns =>
                                {
                                    columns.ConstantColumn(30);  // ID
                                    columns.RelativeColumn(3);  // Name
                                    columns.RelativeColumn(2.5f); // Expertise
                                    columns.ConstantColumn(58); // Rate (PKR)
                                    columns.ConstantColumn(45); // Completed
                                    columns.ConstantColumn(40); // Rating
                                    columns.ConstantColumn(45); // Complaints
                                    columns.ConstantColumn(50); // Status
                                });

                                // Header
                                table.Header(header =>
                                {
                                    header.Cell().Background("#1E3A8A").Padding(5).AlignCenter().Text("ID").Bold().FontColor("#FFFFFF");
                                    header.Cell().Background("#1E3A8A").Padding(5).Text("Provider Name").Bold().FontColor("#FFFFFF");
                                    header.Cell().Background("#1E3A8A").Padding(5).Text("Expertise").Bold().FontColor("#FFFFFF");
                                    header.Cell().Background("#1E3A8A").Padding(5).AlignCenter().Text("Rate (PKR)").Bold().FontColor("#FFFFFF");
                                    header.Cell().Background("#1E3A8A").Padding(5).AlignCenter().Text("Jobs").Bold().FontColor("#FFFFFF");
                                    header.Cell().Background("#1E3A8A").Padding(5).AlignCenter().Text("Rating").Bold().FontColor("#FFFFFF");
                                    header.Cell().Background("#1E3A8A").Padding(5).AlignCenter().Text("Issues").Bold().FontColor("#FFFFFF");
                                    header.Cell().Background("#1E3A8A").Padding(5).AlignCenter().Text("Status").Bold().FontColor("#FFFFFF");
                                });

                                // Rows
                                if (report.SpPerformance != null && report.SpPerformance.Count > 0)
                                {
                                    for (int i = 0; i < report.SpPerformance.Count; i++)
                                    {
                                        var item = report.SpPerformance[i];
                                        var bg = (i % 2 == 0) ? "#FFFFFF" : "#F8FAFC";

                                        table.Cell().Background(bg).BorderBottom(1).BorderColor("#E2E8F0").Padding(4).AlignCenter().Text(item.Id);
                                        table.Cell().Background(bg).BorderBottom(1).BorderColor("#E2E8F0").Padding(4).Text(item.Name).Bold();
                                        table.Cell().Background(bg).BorderBottom(1).BorderColor("#E2E8F0").Padding(4).Text(item.Expertise ?? "General");
                                        table.Cell().Background(bg).BorderBottom(1).BorderColor("#E2E8F0").Padding(4).AlignCenter().Text($"PKR {item.HourlyRate:0}");
                                        table.Cell().Background(bg).BorderBottom(1).BorderColor("#E2E8F0").Padding(4).AlignCenter().Text(item.CompletedJobs.ToString());
                                        table.Cell().Background(bg).BorderBottom(1).BorderColor("#E2E8F0").Padding(4).AlignCenter().Text($"{item.AverageRating:0.0}");
                                        table.Cell().Background(bg).BorderBottom(1).BorderColor("#E2E8F0").Padding(4).AlignCenter().Text(item.ComplaintsReceived.ToString());
                                        table.Cell().Background(bg).BorderBottom(1).BorderColor("#E2E8F0").Padding(4).AlignCenter().Text(item.Status);
                                    }
                                }
                            }
                        });
                    });

                    // Footer
                    page.Footer().Column(col =>
                    {
                        col.Item().LineHorizontal(1).LineColor("#E2E8F0");
                        col.Item().PaddingTop(4).Row(row =>
                        {
                            row.RelativeItem().Text("Smart Home Maintenance Service (SHMS) • Confidential & Proprietary")
                                .FontSize(8).FontColor("#94A3B8");
                            row.ConstantItem(100).AlignRight().Text(text =>
                            {
                                text.Span("Page ").FontSize(8).FontColor("#94A3B8");
                                text.CurrentPageNumber().FontSize(8).FontColor("#94A3B8");
                                text.Span(" of ").FontSize(8).FontColor("#94A3B8");
                                text.TotalPages().FontSize(8).FontColor("#94A3B8");
                            });
                        });
                    });
                });
            });

            return document.GeneratePdf();
        }
    }
}
